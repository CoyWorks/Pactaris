// Generates docs/schema/<component>.md from the migrations, so the current database layout is
// readable without replaying 90+ migration files (docs/schema/README.md).
//
//   TEST_DATABASE_URL=postgresql://postgres@host/postgres npm run schema:snapshot   # write
//   TEST_DATABASE_URL=...                                     npm run schema:check      # CI: fail if stale
//
// It creates a throwaway database and roles, applies the migrations with the real migration
// runner, reads the PostgreSQL catalog and removes everything again. Developer tooling only.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
import pg from 'pg';
import {migrate,migrations,type Component} from '../packages/db/migrations.js';

const components:Component[]=['gateway','instance'];
const out='docs/schema';

type Row=Record<string,unknown>;
async function rows(pool:pg.Pool,sql:string,args:unknown[]=[]):Promise<Row[]>{return (await pool.query(sql,args)).rows;}

function databaseUrl(admin:string,database:string,user?:string,password?:string){
  const u=new URL(admin);u.pathname='/'+database;if(user){u.username=user;u.password=password??'';}return u.href;
}

async function describe(pool:pg.Pool,runtime:string,backup:string,component:Component,count:number):Promise<string>{
  const ns="n.nspname='pactaris'";
  const tables=await rows(pool,`SELECT c.oid,c.relname,c.relrowsecurity,c.relforcerowsecurity FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE ${ns} AND c.relkind IN ('r','p') ORDER BY c.relname`);
  const columns=await rows(pool,`SELECT c.relname,a.attname,format_type(a.atttypid,a.atttypmod) AS type,a.attnotnull,pg_get_expr(d.adbin,d.adrelid) AS def
    FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
    WHERE ${ns} AND c.relkind IN ('r','p') AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum`);
  const constraints=await rows(pool,`SELECT c.relname,k.conname,k.contype,pg_get_constraintdef(k.oid) AS def,f.relname AS target
    FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace LEFT JOIN pg_class f ON f.oid=k.confrelid
    WHERE ${ns} AND k.contype IN ('p','u','f','c','x') ORDER BY c.relname,k.contype,k.conname`);
  const indexes=await rows(pool,`SELECT i.tablename,i.indexname,i.indexdef FROM pg_indexes i
    WHERE i.schemaname='pactaris' AND NOT EXISTS(SELECT 1 FROM pg_constraint k WHERE k.conname=i.indexname AND k.connamespace='pactaris'::regnamespace)
    ORDER BY i.tablename,i.indexname`);
  const policies=await rows(pool,`SELECT tablename,policyname,cmd,array_to_string(roles,',') AS roles,qual,with_check FROM pg_policies WHERE schemaname='pactaris' ORDER BY tablename,policyname`);
  const triggers=await rows(pool,`SELECT c.relname,t.tgname,p.proname FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
    JOIN pg_proc p ON p.oid=t.tgfoid WHERE ${ns} AND NOT t.tgisinternal ORDER BY c.relname,t.tgname`);
  const functions=await rows(pool,`SELECT p.proname,pg_get_function_identity_arguments(p.oid) AS args,p.prosecdef,
    has_function_privilege($1,p.oid,'EXECUTE') AS runtime FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE ${ns} ORDER BY p.proname,args`,[runtime]);
  const privileges=await rows(pool,`SELECT c.relname,
    array_to_string(ARRAY(SELECT x FROM unnest(ARRAY['SELECT','INSERT','UPDATE','DELETE']) x WHERE has_table_privilege($1,c.oid,x)),',') AS runtime,
    EXISTS(SELECT 1 FROM unnest(ARRAY['SELECT','INSERT','UPDATE']) x WHERE has_any_column_privilege($1,c.oid,x)) AS columns
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE ${ns} AND c.relkind IN ('r','p') ORDER BY c.relname`,[runtime]);

  // Role names are throwaway; show them by purpose so the snapshot is stable.
  const roleName=(value:unknown)=>String(value??'').replaceAll(runtime,'{runtime}').replaceAll(backup,'{backup}');
  const cell=(value:unknown)=>String(value??'').replaceAll('|','\\|').replaceAll('\n',' ').replace(/\s+/g,' ').trim();
  const by=<T extends Row>(list:T[],key:string)=>{const map=new Map<string,T[]>();for(const r of list){const k=String(r[key]);map.set(k,[...(map.get(k)??[]),r]);}return map;};
  const colsBy=by(columns,'relname'),consBy=by(constraints,'relname'),idxBy=by(indexes,'tablename'),polBy=by(policies,'tablename'),trgBy=by(triggers,'relname');
  const privBy=new Map(privileges.map(p=>[String(p.relname),p]));

  const fkEdges=new Set<string>();
  for(const k of constraints)if(k.contype==='f'&&k.target&&k.target!==k.relname)fkEdges.add(`  ${k.relname} }o--|| ${k.target} : ""`);

  const lines:string[]=[];
  lines.push(`# ${component === 'gateway' ? 'Gateway' : 'Instance'} database schema`,'',
    '<!-- Generated by scripts/schema-snapshot.ts from the migrations. Do not edit by hand: run `npm run schema:snapshot`. -->','',
    `Schema \`pactaris\` after ${count} migrations: ${tables.length} tables, ${functions.length} functions. `+
    'How to read this page and the access model: [README.md](README.md).','');
  lines.push('## Tables','','| Table | Columns | Row-level security | Runtime access |','|---|---|---|---|');
  for(const t of tables){
    const name=String(t.relname),p=privBy.get(name);
    const access=p?.runtime?String(p.runtime):p?.columns?'some columns':'functions only';
    lines.push(`| [${name}](#${name}) | ${(colsBy.get(name)??[]).length} | ${t.relrowsecurity?(t.relforcerowsecurity?'forced':'on'):'off'} | ${access} |`);
  }
  lines.push('','## Relations','','Foreign keys between tables (most also carry `household_id`, so a row can only point inside its own dynamic).','',
    '```mermaid','erDiagram',...[...fkEdges].sort(),'```','');
  for(const t of tables){
    const name=String(t.relname);
    lines.push(`### ${name}`,'','| Column | Type | Null | Default |','|---|---|---|---|');
    for(const c of colsBy.get(name)??[])lines.push(`| ${c.attname} | ${cell(c.type)} | ${c.attnotnull?'not null':'null'} | ${cell(c.def)} |`);
    const cons=consBy.get(name)??[];
    if(cons.length){lines.push('','| Constraint | Definition |','|---|---|');for(const k of cons)lines.push(`| ${k.conname} | ${cell(k.def)} |`);}
    const idx=idxBy.get(name)??[];
    if(idx.length){lines.push('','Indexes:','');for(const i of idx)lines.push(`- \`${cell(i.indexdef).replace('ON pactaris.','ON ')}\``);}
    const pol=polBy.get(name)??[];
    if(pol.length){lines.push('','Policies:','');for(const p of pol)lines.push(`- **${p.policyname}** (${p.cmd}, ${roleName(p.roles)}): \`${cell(roleName(p.qual??p.with_check))}\``);}
    const trg=trgBy.get(name)??[];
    if(trg.length){lines.push('','Triggers: '+trg.map(x=>`\`${x.tgname}\` → \`${x.proname}()\``).join(', '));}
    lines.push('');
  }
  if(functions.length){
    lines.push('## Functions','','`SECURITY DEFINER` functions run with the owner\'s rights and do their own tenant, consent and safety checks; '+
      'the runtime role can call only those marked *runtime*. Names ending in `_before_<feature>` are earlier layers that a newer function wraps.','',
      '| Function | Arguments | Security | Runtime |','|---|---|---|---|');
    for(const f of functions)lines.push(`| ${f.proname} | ${cell(f.args)} | ${f.prosecdef?'definer':'invoker'} | ${f.runtime?'yes':''} |`);
    lines.push('');
  }
  return lines.join('\n');
}

async function snapshot(admin:string,component:Component):Promise<string>{
  const suffix=randomBytes(4).toString('hex'),database=`pactaris_schema_${component}_${suffix}`;
  const runtime=`${database}_runtime`,migration=`${database}_migration`,backup=`${database}_backup`,password=randomBytes(18).toString('base64url');
  const root=new pg.Pool({connectionString:admin,max:1});
  const pools:pg.Pool[]=[];
  try{
    for(const [role,flags] of [[runtime,'NOBYPASSRLS'],[migration,'NOBYPASSRLS'],[backup,'BYPASSRLS']])
      await root.query(`CREATE ROLE "${role}" LOGIN PASSWORD '${password}' NOSUPERUSER NOCREATEDB NOCREATEROLE ${flags}`);
    await root.query(`CREATE DATABASE "${database}"`);
    await root.query(`REVOKE ALL ON DATABASE "${database}" FROM PUBLIC;GRANT CONNECT ON DATABASE "${database}" TO "${runtime}","${migration}","${backup}";GRANT CREATE ON DATABASE "${database}" TO "${migration}"`);
    const migrator=new pg.Pool({connectionString:databaseUrl(admin,database,migration,password),max:1});pools.push(migrator);
    await migrate(migrator,process.cwd(),component,runtime,backup);
    const reader=new pg.Pool({connectionString:databaseUrl(admin,database),max:1});pools.push(reader);
    return await describe(reader,runtime,backup,component,(await migrations(process.cwd(),component)).length);
  }finally{
    await Promise.all(pools.map(p=>p.end()));
    await root.query(`DROP DATABASE IF EXISTS "${database}"`);
    for(const role of [runtime,migration,backup])await root.query(`DROP ROLE IF EXISTS "${role}"`);
    await root.end();
  }
}

async function main(){
  const admin=process.env.TEST_DATABASE_URL,check=process.argv.includes('--check');
  if(!admin){process.stderr.write(JSON.stringify({code:'schema.database_required'})+'\n');process.exit(2);}
  await mkdir(out,{recursive:true});
  const stale:string[]=[];
  for(const component of components){
    const text=await snapshot(admin,component)+'\n',path=`${out}/${component}.md`;
    if(check){if(await readFile(path,'utf8').catch(()=>'')!==text)stale.push(path);}
    else await writeFile(path,text);
  }
  if(stale.length){process.stderr.write(JSON.stringify({code:'schema.stale',files:stale,fix:'npm run schema:snapshot'})+'\n');process.exit(1);}
  process.stdout.write(JSON.stringify({code:check?'schema.current':'schema.written',components})+'\n');
}
await main();
