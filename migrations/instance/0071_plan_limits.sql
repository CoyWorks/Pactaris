-- Plan limits on the Instance (docs/HOUSEHOLD_PLANS.md, owner decisions 26-28 November 2026).
-- The gateway sends the limits as capabilities (0070). This migration enforces them when something new
-- is created, or when an item comes back into use (reopened, restored). It never deletes, stops or
-- changes existing items; completing, archiving, cancelling and pausing are never refused.
--
-- Per person: open one-off tasks (the assignee, or the creator for own and unassigned tasks), repeating
-- tasks (the assignee; the owner of a personal series), Dom-set habits (the sub) and routines (the
-- creator). Per dynamic: rewards, punishments (consequences) and shop items.
-- Occurrences generated by a series count towards the series, not towards one-off tasks.
-- A household that never received its plan uses the Free values below (same as packages/auth/plans.ts).

CREATE FUNCTION pactaris.plan_limit(target uuid,key text) RETURNS integer
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
DECLARE raw text;
BEGIN
 SELECT capabilities->>key INTO raw FROM pactaris.household_entitlements WHERE household_id=target;
 IF raw~'^[0-9]{1,5}$' THEN RETURN raw::integer; END IF;
 RETURN CASE key WHEN 'members.active.max' THEN 4 WHEN 'oneoff.open.max' THEN 10 WHEN 'series.active.max' THEN 3
  WHEN 'habits.assigned.max' THEN 3 WHEN 'routines.active.max' THEN 3 WHEN 'plan.horizon.days' THEN 14
  WHEN 'catalog.rewards.max' THEN 5 WHEN 'catalog.punishments.max' THEN 5 WHEN 'shop.items.max' THEN 5
  WHEN 'history.days' THEN 30 ELSE 0 END;
END $$;
REVOKE ALL ON FUNCTION pactaris.plan_limit(uuid,text) FROM PUBLIC;

-- What one person uses now; `catalog`/`shop` keys are per dynamic and ignore `person`.
CREATE FUNCTION pactaris.plan_used(target uuid,key text,person uuid) RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
 SELECT CASE key
  WHEN 'oneoff.open.max' THEN
   (SELECT count(*) FROM pactaris.tasks WHERE household_id=target AND state='open' AND personal_series_id IS NULL
     AND coalesce(assignee_membership_id,creator_membership_id)=person)
   +(SELECT count(*) FROM pactaris.partner_tasks WHERE household_id=target AND series_id IS NULL AND assignee_id=person
     AND state NOT IN ('done','declined','cancelled'))
  WHEN 'series.active.max' THEN
   (SELECT count(*) FROM pactaris.task_series WHERE household_id=target AND assignee_id=person AND state IN ('active','blocked'))
   +(SELECT count(*) FROM pactaris.personal_task_series WHERE household_id=target AND creator_id=person AND state IN ('active','blocked'))
  WHEN 'habits.assigned.max' THEN
   (SELECT count(*) FROM pactaris.authority_habits WHERE household_id=target AND subject_id=person AND state IN ('active','paused'))
  WHEN 'routines.active.max' THEN
   (SELECT count(*) FROM pactaris.routines WHERE household_id=target AND creator_membership_id=person AND state IN ('draft','active','paused'))
  WHEN 'catalog.rewards.max' THEN
   (SELECT count(*) FROM pactaris.catalog_items i JOIN pactaris.catalog_versions v ON v.household_id=i.household_id AND v.item_id=i.id AND v.version=i.version
     WHERE i.household_id=target AND i.state='draft' AND coalesce(v.fields->>'kind','reward')<>'consequence')
  WHEN 'catalog.punishments.max' THEN
   (SELECT count(*) FROM pactaris.catalog_items i JOIN pactaris.catalog_versions v ON v.household_id=i.household_id AND v.item_id=i.id AND v.version=i.version
     WHERE i.household_id=target AND i.state='draft' AND v.fields->>'kind'='consequence')
  WHEN 'shop.items.max' THEN
   (SELECT count(*) FROM pactaris.shop_listings WHERE household_id=target)
  WHEN 'members.active.max' THEN
   (SELECT count(*) FROM pactaris.memberships WHERE household_id=target AND status='active')
  ELSE 0 END::integer
$$;
REVOKE ALL ON FUNCTION pactaris.plan_used(uuid,text,uuid) FROM PUBLIC;

-- Tasks and series: replaces the pilot's shared `tasks.active.max` count with the per-person plan limits.
-- The messages stay the modules' own capacity keys, which the apps already map.
CREATE OR REPLACE FUNCTION pactaris.combined_task_capacity() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
DECLARE limit_key text;person uuid;message text;
BEGIN
 IF TG_TABLE_NAME='tasks' THEN
  IF NEW.state<>'open' OR NEW.personal_series_id IS NOT NULL THEN RETURN NEW;END IF;
  IF TG_OP='UPDATE' THEN IF OLD.state='open' THEN RETURN NEW;END IF;END IF;
  limit_key='oneoff.open.max';person=coalesce(NEW.assignee_membership_id,NEW.creator_membership_id);message='workspace.capacity';
 ELSIF TG_TABLE_NAME='task_series' THEN
  IF NEW.state NOT IN ('active','blocked') THEN RETURN NEW;END IF;
  IF TG_OP='UPDATE' THEN IF OLD.state IN ('active','blocked') THEN RETURN NEW;END IF;END IF;
  limit_key='series.active.max';person=NEW.assignee_id;message='partner.capacity';
 ELSIF TG_TABLE_NAME='personal_task_series' THEN
  IF NEW.state NOT IN ('active','blocked') THEN RETURN NEW;END IF;
  IF TG_OP='UPDATE' THEN IF OLD.state IN ('active','blocked') THEN RETURN NEW;END IF;END IF;
  -- A revision first marks its predecessor superseded, which no longer counts, so revising never adds one.
  limit_key='series.active.max';person=NEW.creator_id;message='workspace.capacity';
 ELSE
  IF NEW.state IN ('done','declined','cancelled') OR NEW.series_id IS NOT NULL THEN RETURN NEW;END IF;
  IF TG_OP='UPDATE' THEN IF OLD.state NOT IN ('done','declined','cancelled') THEN RETURN NEW;END IF;END IF;
  limit_key='oneoff.open.max';person=NEW.assignee_id;message='partner.capacity';
 END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('pactaris.household.'||NEW.household_id::text,0));
 IF pactaris.plan_used(NEW.household_id,limit_key,person)>=pactaris.plan_limit(NEW.household_id,limit_key) THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE=message;
 END IF;
 RETURN NEW;
END $$;

-- Dom-set habits (per sub) and routines (per creator): a new item, or one restored from the archive.
-- Pausing does not free a place, so resuming a paused item is never refused.
CREATE FUNCTION pactaris.plan_item_capacity() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
DECLARE limit_key text;person uuid;
BEGIN
 IF NEW.state='archived' THEN RETURN NEW;END IF;
 IF TG_OP='UPDATE' THEN IF OLD.state<>'archived' THEN RETURN NEW;END IF;END IF;
 IF TG_TABLE_NAME='authority_habits' THEN limit_key='habits.assigned.max';person=NEW.subject_id;
 ELSE limit_key='routines.active.max';person=NEW.creator_membership_id; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('pactaris.household.'||NEW.household_id::text,0));
 IF pactaris.plan_used(NEW.household_id,limit_key,person)>=pactaris.plan_limit(NEW.household_id,limit_key) THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='plan.limit';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION pactaris.plan_item_capacity() FROM PUBLIC;
CREATE TRIGGER plan_habit_capacity BEFORE INSERT OR UPDATE OF state ON pactaris.authority_habits FOR EACH ROW EXECUTE FUNCTION pactaris.plan_item_capacity();
CREATE TRIGGER plan_routine_capacity BEFORE INSERT OR UPDATE OF state ON pactaris.routines FOR EACH ROW EXECUTE FUNCTION pactaris.plan_item_capacity();

-- Rewards and punishments: the kind is known when the first version is written, right after the item.
CREATE FUNCTION pactaris.plan_catalog_capacity() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
DECLARE limit_key text;
BEGIN
 IF NEW.version<>1 THEN RETURN NEW;END IF;
 limit_key=CASE WHEN NEW.fields->>'kind'='consequence' THEN 'catalog.punishments.max' ELSE 'catalog.rewards.max' END;
 PERFORM pg_advisory_xact_lock(hashtextextended('pactaris.household.'||NEW.household_id::text,0));
 -- The new item already exists (state draft) without a version, so the count above excludes it.
 IF pactaris.plan_used(NEW.household_id,limit_key,NULL)>=pactaris.plan_limit(NEW.household_id,limit_key) THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='plan.limit';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION pactaris.plan_catalog_capacity() FROM PUBLIC;
CREATE TRIGGER plan_catalog_capacity BEFORE INSERT ON pactaris.catalog_versions FOR EACH ROW EXECUTE FUNCTION pactaris.plan_catalog_capacity();

-- Shop items: a new listing. Saving an item that is already listed (ON CONFLICT ... DO UPDATE) is not new.
CREATE FUNCTION pactaris.plan_shop_capacity() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM pactaris.shop_listings WHERE household_id=NEW.household_id AND item_id=NEW.item_id) THEN RETURN NEW;END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('pactaris.household.'||NEW.household_id::text,0));
 IF pactaris.plan_used(NEW.household_id,'shop.items.max',NULL)>=pactaris.plan_limit(NEW.household_id,'shop.items.max') THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='plan.limit';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION pactaris.plan_shop_capacity() FROM PUBLIC;
CREATE TRIGGER plan_shop_capacity BEFORE INSERT ON pactaris.shop_listings FOR EACH ROW EXECUTE FUNCTION pactaris.plan_shop_capacity();

-- The Plan panel: the caller's own use and the dynamic's use, next to each limit.
CREATE FUNCTION pactaris.plan_usage(target uuid,instance uuid,actor uuid,body jsonb) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,pactaris,pg_temp AS $$
DECLARE m pactaris.memberships;usage jsonb='{}'::jsonb;k text;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM pactaris.households WHERE id=target AND instance_id=instance AND status<>'closed') THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='workspace.denied'; END IF;
 SELECT * INTO m FROM pactaris.memberships WHERE household_id=target AND id=(body->>'membershipId')::uuid AND account_id=actor AND status='active';
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='workspace.denied'; END IF;
 FOREACH k IN ARRAY ARRAY['members.active.max','oneoff.open.max','series.active.max','habits.assigned.max','routines.active.max',
  'catalog.rewards.max','catalog.punishments.max','shop.items.max'] LOOP
  usage=usage||jsonb_build_object(k,jsonb_build_object('used',pactaris.plan_used(target,k,m.id),'limit',pactaris.plan_limit(target,k)));
 END LOOP;
 RETURN jsonb_build_object('householdId',target,'operationId',body->>'operationId','actorMembershipId',m.id,'status','listed','usage',usage);
END $$;
REVOKE ALL ON FUNCTION pactaris.plan_usage(uuid,uuid,uuid,jsonb) FROM PUBLIC;

-- Retire the pilot's shared `tasks.active.max` (25 per dynamic). workspace_command (0009) still compares
-- open tasks with it; a value no dynamic reaches leaves the per-person plan limits above as the limit.
UPDATE pactaris.household_entitlements SET capabilities=capabilities||'{"tasks.active.max":999999}'::jsonb,version=version+1;
CREATE OR REPLACE FUNCTION pactaris.task_default_capacity() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pactaris,pg_temp AS $$
BEGIN NEW.capabilities=NEW.capabilities||'{"tasks.active.max":999999}'::jsonb; RETURN NEW; END $$;
